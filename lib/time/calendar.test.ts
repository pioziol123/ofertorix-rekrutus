import { describe, expect, it } from 'vitest'
import { dayStart, monthStart, polishDay, polishMonth } from './index.ts'

const at = (iso: string) => new Date(iso)

describe('Polish day and month of a moment (T6-AC01)', () => {
  it.each([
    // winter midnight (UTC+1)
    ['2026-01-14T22:59:59.999Z', '2026-01-14', '2026-01'],
    ['2026-01-14T23:00:00.000Z', '2026-01-15', '2026-01'],
    // summer midnight (UTC+2)
    ['2026-07-14T21:59:59.999Z', '2026-07-14', '2026-07'],
    ['2026-07-14T22:00:00.000Z', '2026-07-15', '2026-07'],
    // spring change day: 02:00 CET jumps to 03:00 CEST at 01:00 UTC
    ['2026-03-28T22:59:59.999Z', '2026-03-28', '2026-03'],
    ['2026-03-28T23:00:00.000Z', '2026-03-29', '2026-03'],
    ['2026-03-29T00:59:59.999Z', '2026-03-29', '2026-03'],
    ['2026-03-29T01:00:00.000Z', '2026-03-29', '2026-03'],
    ['2026-03-29T21:59:59.999Z', '2026-03-29', '2026-03'],
    ['2026-03-29T22:00:00.000Z', '2026-03-30', '2026-03'],
    // autumn change day: 03:00 CEST goes back to 02:00 CET at 01:00 UTC
    ['2026-10-24T21:59:59.999Z', '2026-10-24', '2026-10'],
    ['2026-10-24T22:00:00.000Z', '2026-10-25', '2026-10'],
    ['2026-10-25T00:30:00.000Z', '2026-10-25', '2026-10'],
    ['2026-10-25T01:30:00.000Z', '2026-10-25', '2026-10'],
    ['2026-10-25T22:59:59.999Z', '2026-10-25', '2026-10'],
    ['2026-10-25T23:00:00.000Z', '2026-10-26', '2026-10'],
    // month turn at a time change offset: November starts in winter time
    ['2026-10-31T22:59:59.999Z', '2026-10-31', '2026-10'],
    ['2026-10-31T23:00:00.000Z', '2026-11-01', '2026-11'],
    // turn of a year
    ['2026-12-31T22:59:59.999Z', '2026-12-31', '2026-12'],
    ['2026-12-31T23:00:00.000Z', '2027-01-01', '2027-01'],
    // 29 February
    ['2028-02-28T22:59:59.999Z', '2028-02-28', '2028-02'],
    ['2028-02-28T23:00:00.000Z', '2028-02-29', '2028-02'],
    ['2028-02-29T22:59:59.999Z', '2028-02-29', '2028-02'],
    ['2028-02-29T23:00:00.000Z', '2028-03-01', '2028-03'],
  ])('%s is the Polish day %s of month %s', (moment, day, month) => {
    expect(polishDay(at(moment))).toBe(day)
    expect(polishMonth(at(moment))).toBe(month)
  })
})

describe('start of the Polish day in UTC (T6-AC01)', () => {
  it.each([
    ['2026-01-15T10:00:00Z', 0, '2026-01-14T23:00:00.000Z'],
    ['2026-01-14T23:00:00Z', 0, '2026-01-14T23:00:00.000Z'],
    ['2026-01-14T22:59:59Z', 0, '2026-01-13T23:00:00.000Z'],
    ['2026-07-15T10:00:00Z', 0, '2026-07-14T22:00:00.000Z'],
    ['2026-07-14T22:00:00Z', 1, '2026-07-13T22:00:00.000Z'],
    // the spring change day starts in winter time and lasts 23 hours
    ['2026-03-29T12:00:00Z', 0, '2026-03-28T23:00:00.000Z'],
    ['2026-03-30T10:00:00Z', 0, '2026-03-29T22:00:00.000Z'],
    ['2026-03-30T10:00:00Z', 1, '2026-03-28T23:00:00.000Z'],
    ['2026-04-04T10:00:00Z', 7, '2026-03-27T23:00:00.000Z'],
    // the autumn change day starts in summer time and lasts 25 hours
    ['2026-10-25T01:30:00Z', 0, '2026-10-24T22:00:00.000Z'],
    ['2026-10-26T10:00:00Z', 0, '2026-10-25T23:00:00.000Z'],
    ['2026-10-26T10:00:00Z', 1, '2026-10-24T22:00:00.000Z'],
    ['2026-10-31T10:00:00Z', 29, '2026-10-01T22:00:00.000Z'],
    // turn of a year and 29 February
    ['2027-01-01T05:00:00Z', 0, '2026-12-31T23:00:00.000Z'],
    ['2027-01-01T05:00:00Z', 1, '2026-12-30T23:00:00.000Z'],
    ['2028-03-01T05:00:00Z', 1, '2028-02-28T23:00:00.000Z'],
    ['2028-02-29T12:00:00Z', 0, '2028-02-28T23:00:00.000Z'],
  ])('%s, %i days back, starts at %s', (moment, back, start) => {
    expect(dayStart(at(moment), back).toISOString()).toBe(start)
  })
})

describe('start of the Polish month in UTC (T6-AC01)', () => {
  it.each([
    ['2026-01-20T10:00:00Z', 0, '2025-12-31T23:00:00.000Z'],
    ['2026-07-20T10:00:00Z', 0, '2026-06-30T22:00:00.000Z'],
    ['2026-03-31T21:59:59Z', 0, '2026-02-28T23:00:00.000Z'],
    ['2026-03-31T22:00:00Z', 0, '2026-03-31T22:00:00.000Z'],
    ['2026-04-10T10:00:00Z', 1, '2026-02-28T23:00:00.000Z'],
    ['2026-11-10T10:00:00Z', 0, '2026-10-31T23:00:00.000Z'],
    ['2026-11-10T10:00:00Z', 1, '2026-09-30T22:00:00.000Z'],
    ['2027-01-01T05:00:00Z', 0, '2026-12-31T23:00:00.000Z'],
    ['2027-01-01T05:00:00Z', 1, '2026-11-30T23:00:00.000Z'],
    ['2028-03-01T00:00:00Z', 0, '2028-02-29T23:00:00.000Z'],
    ['2028-03-01T00:00:00Z', 1, '2028-01-31T23:00:00.000Z'],
    ['2028-02-29T12:00:00Z', 0, '2028-01-31T23:00:00.000Z'],
  ])('%s, %i months back, starts at %s', (moment, back, start) => {
    expect(monthStart(at(moment), back).toISOString()).toBe(start)
  })
})

describe('malformed input', () => {
  it('throws naming an invalid moment', () => {
    expect(() => polishDay(new Date('nope'))).toThrow('Invalid moment')
    expect(() => polishMonth(new Date(Number.NaN))).toThrow('Invalid moment')
  })
  it('throws naming a count that is not a whole number', () => {
    expect(() => dayStart(at('2026-01-01T00:00:00Z'), 1.5)).toThrow('1.5')
    expect(() => monthStart(at('2026-01-01T00:00:00Z'), Number.NaN)).toThrow(
      'NaN',
    )
  })
})
